-- ============================================
-- DALTI — Corrected & Improved Database Schema
-- Supabase PostgreSQL
-- ============================================

-- 1. Users
CREATE TABLE public.users (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,                    -- FIXED: was "passeword_hash"
  first_name text NOT NULL,
  last_name text,
  birth_date date,
  wilaya text,
  commune text,
  is_admin boolean DEFAULT false,
  updated_at timestamptz,
  CONSTRAINT users_pkey PRIMARY KEY (id)
) TABLESPACE pg_default;

-- 2. Structures
CREATE TABLE public.structures (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  name text NOT NULL,
  type text NOT NULL,
  adresse text NOT NULL,
  wilaya text NOT NULL,
  commune text NOT NULL,
  latitude double precision NOT NULL,
  longitude double precision NOT NULL,            -- FIXED: was bigint
  CONSTRAINT structures_pkey PRIMARY KEY (id)
) TABLESPACE pg_default;

-- 3. Services
CREATE TABLE public.services (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  name text NOT NULL,
  description text NOT NULL,
  icon text,
  is_popular boolean NOT NULL DEFAULT false,
  CONSTRAINT services_pkey PRIMARY KEY (id)
) TABLESPACE pg_default;

-- 4. Structure-Services junction
CREATE TABLE public.structure_services (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  structure_id uuid NOT NULL,
  service_id uuid NOT NULL,
  CONSTRAINT structure_services_pkey PRIMARY KEY (id),
  CONSTRAINT structure_services_service_id_fkey FOREIGN KEY (service_id) REFERENCES services(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT structure_services_structure_id_fkey FOREIGN KEY (structure_id) REFERENCES structures(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT structure_services_unique UNIQUE (structure_id, service_id)
) TABLESPACE pg_default;

-- 5. User-Structures (roles)
CREATE TABLE public.user_structures (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  user_id uuid NOT NULL,
  structure_id uuid NOT NULL,
  role text NOT NULL DEFAULT 'admin',
  CONSTRAINT user_structures_pkey PRIMARY KEY (id),
  CONSTRAINT user_structures_structure_id_fkey FOREIGN KEY (structure_id) REFERENCES structures(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT user_structures_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT user_structures_unique UNIQUE (user_id, structure_id)
) TABLESPACE pg_default;

-- 6. Queues
CREATE TABLE public.queues (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  structure_id uuid NOT NULL,
  service_id uuid NOT NULL,
  current_number bigint NOT NULL DEFAULT 0,
  last_called_number bigint DEFAULT 0,
  total_today bigint DEFAULT 0,
  status text NOT NULL DEFAULT 'open',
  CONSTRAINT queues_pkey PRIMARY KEY (id),
  CONSTRAINT queues_service_id_fkey FOREIGN KEY (service_id) REFERENCES services(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT queues_structure_id_fkey FOREIGN KEY (structure_id) REFERENCES structures(id) ON UPDATE CASCADE ON DELETE CASCADE
) TABLESPACE pg_default;

-- 7. Tickets
CREATE TABLE public.tickets (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  user_id uuid NOT NULL,
  queue_id uuid NOT NULL,
  number bigint NOT NULL,
  status text DEFAULT 'waiting',
  qr_code text NOT NULL,
  estimated_time bigint NOT NULL DEFAULT 10,
  actual_wait_time bigint,                        -- FIXED: nullable (unknown at creation)
  called_at timestamptz,                          -- FIXED: was time, now timestamptz
  completed_at timestamptz,                       -- FIXED: was "completed_att" + wrong type
  CONSTRAINT tickets_pkey PRIMARY KEY (id),
  CONSTRAINT tickets_qr_code_key UNIQUE (qr_code),
  CONSTRAINT tickets_queue_id_fkey FOREIGN KEY (queue_id) REFERENCES queues(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT tickets_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL
) TABLESPACE pg_default;

-- 8. Ticket Exchanges
CREATE TABLE public.ticket_exchange (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  ticket_owner_id uuid NOT NULL,
  ticket_target_id uuid NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  CONSTRAINT ticket_exchange_pkey PRIMARY KEY (id),
  CONSTRAINT ticket_exchange_ticket_owner_id_fkey FOREIGN KEY (ticket_owner_id) REFERENCES tickets(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT ticket_exchange_ticket_target_id_fkey FOREIGN KEY (ticket_target_id) REFERENCES tickets(id) ON UPDATE CASCADE ON DELETE CASCADE
) TABLESPACE pg_default;

-- 9. Notifications
CREATE TABLE public.notifications (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  user_id uuid,
  ticket_id uuid,
  type text DEFAULT 'reminder',
  message text,
  is_sent boolean DEFAULT false,
  scheduled_at timestamptz NOT NULL,
  sent_at timestamptz,                            -- ADDED: missing column
  CONSTRAINT notifications_pkey PRIMARY KEY (id),
  CONSTRAINT notifications_ticket_id_fkey FOREIGN KEY (ticket_id) REFERENCES tickets(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT notifications_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL
) TABLESPACE pg_default;

-- 10. Admin Actions
CREATE TABLE public.admin_actions (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  admin_id uuid,
  ticket_id uuid,
  action text,
  complaint text,                                 -- ADDED: missing column
  CONSTRAINT admin_actions_pkey PRIMARY KEY (id),
  CONSTRAINT admin_actions_admin_id_fkey FOREIGN KEY (admin_id) REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL,
  CONSTRAINT admin_actions_ticket_id_fkey FOREIGN KEY (ticket_id) REFERENCES tickets(id) ON UPDATE CASCADE ON DELETE SET NULL
) TABLESPACE pg_default;

-- ============================================
-- INDEXES — Performance optimization
-- ============================================

CREATE INDEX idx_tickets_queue_status ON tickets(queue_id, status);
CREATE INDEX idx_tickets_user_id ON tickets(user_id);
CREATE INDEX idx_tickets_qr_code ON tickets(qr_code);
CREATE INDEX idx_tickets_created_at ON tickets(created_at DESC);
CREATE INDEX idx_queues_structure ON queues(structure_id);
CREATE INDEX idx_queues_structure_service ON queues(structure_id, service_id);
CREATE INDEX idx_queues_status ON queues(status);
CREATE INDEX idx_notifications_pending ON notifications(scheduled_at) WHERE is_sent = false;
CREATE INDEX idx_structures_wilaya ON structures(wilaya);
CREATE INDEX idx_structure_services_lookup ON structure_services(structure_id, service_id);
CREATE INDEX idx_user_structures_user ON user_structures(user_id);
CREATE INDEX idx_ticket_exchange_status ON ticket_exchange(status) WHERE status = 'pending';
CREATE INDEX idx_admin_actions_ticket ON admin_actions(ticket_id);
CREATE INDEX idx_users_email ON users(email);
